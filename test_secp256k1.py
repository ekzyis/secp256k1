    def test_serialize(self):
        compressed_G = bytes.fromhex(
            "02" +
            "79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798")
        pub = PublicKey(compressed_G)
        self.assertEqual(pub, G)
        self.assertEqual(pub.serialize(), compressed_G)

        uncompressed_G = bytes.fromhex(
            "04" +
            "79be667ef9dcbbac55a06295ce870b07029bfcdb2dce28d959f2815b16f81798" +
            "483ada7726a3c4655da4fbfc0e1108a8fd17b448a68554199c47d08ffb10d4b8"
        )
        pub = PublicKey(uncompressed_G)
        self.assertEqual(pub, G)
        self.assertEqual(pub.serialize_uncompressed(), uncompressed_G)

    def test_private_key_tweak_add(self):
        priv = PrivateKey(bytes.fromhex("532b4439bc2ca9409866c81daf77b2514568b8da3706479375724c270864d1db"))  # noqa
        tweak = bytes.fromhex("d562ae151c144dc96d81a7a94092559a00a141c859238ce86c1540d84ea6f513")  # noqa
        tweaked_key = PrivateKey(bytes.fromhex("288df24ed840f70a05e86fc6f00a07ec8b5b1dbbe0e1344021b52e7286d585ad"))  # noqa
        self.assertEqual(priv.tweak_add(tweak), tweaked_key)

    def test_public_key_tweak_add(self):
        pub = PublicKey(bytes.fromhex("0220bd00ab6345b7dca52e0ee8e7c6af505dff2b77b68646c3580d64badb50c6c1"))  # noqa
        tweak = bytes.fromhex("b016df28964a4f31e1021fd3f02cb05a407c3825ecc11731786b7bb80436b413")  # noqa
        tweaked_key = PublicKey(bytes.fromhex("03b4eb5a087ad7a992622f2b9558cf37447c34bb796c26506113c80e79b8894ea3"))  # noqa
        self.assertEqual(pub.tweak_add(tweak), tweaked_key)

    def test_public_key_tweak_mul(self):
        pub = PublicKey(bytes.fromhex("03f5a23765ec4ee738007911894b2f3567d2eaac69c03d54d2ee9b46597a8aefba"))  # noqa
        tweak = (N-1).to_bytes(32, "big")  # minus-one
        tweaked_key = PublicKey(bytes.fromhex("02f5a23765ec4ee738007911894b2f3567d2eaac69c03d54d2ee9b46597a8aefba"))  # noqa
        self.assertEqual(pub.tweak_mul(tweak), tweaked_key)


